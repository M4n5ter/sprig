def bounded_json(path):
    path = base.ordinary_path(path)
    info = base.check_node(path)
    require(info.st_size <= MIB, "Report/marker exceeds the 1 MiB input bound")
    value = json.loads(path.read_text(encoding="utf-8"))
    require(isinstance(value, dict), "Expected a JSON object")
    return value


def plain_component(value):
    return (isinstance(value, str) and bool(value) and value not in (".", "..")
            and not value.endswith((".", " ")) and len(value) <= 255
            and all(32 <= ord(c) < 127 and c not in '<>:"/\\|?*' for c in value)
            and value.split(".", 1)[0].upper() not in
            {"CON", "PRN", "AUX", "NUL", *("COM%d" % i for i in range(1, 10)),
             *("LPT%d" % i for i in range(1, 10))})


def tree_node(path):
    info = Path(path).lstat()
    require(not stat.S_ISLNK(info.st_mode) and not base.is_reparse(info),
            "Cargo tree refuses links/reparse points: " + str(path))
    require(stat.S_ISREG(info.st_mode) or stat.S_ISDIR(info.st_mode),
            "Cargo tree expects ordinary files/directories: " + str(path))
    require(not getattr(info, "st_file_attributes", 0) & 1,
            "Read-only attributes are outside the writable Cargo contract")
    if stat.S_ISREG(info.st_mode):
        require(0 <= info.st_size <= MAX_FILE_BYTES, "Cargo file exceeds 16 MiB")
        require(1 <= info.st_nlink <= MAX_ENTRIES and info.st_ino != 0,
                "Cargo file has unavailable identity or excessive hardlinks")
    require(info.st_mtime_ns % 100 == 0 if os.name == "nt" else True,
            "Cargo mtime is not Windows-compatible")
    base.stream_check(path)
    return info


def stable_info(info):
    return (info.st_dev, info.st_ino, info.st_mode, info.st_size, info.st_nlink,
            info.st_mtime_ns, getattr(info, "st_file_attributes", 0))


def inventory(root):
    """Hash every byte and compare supported metadata and hardlink topology.

    Directory byte lengths are filesystem implementation details, not payloads.
    Link groups use sorted relative names, never machine-specific inode numbers.
    External hardlinks are refused: the complete group must be in this tree.
    """
    root = Path(root)
    require(stat.S_ISDIR(tree_node(root).st_mode), "Cargo root must be a directory")
    entries, identities, observations = {}, {}, {}
    logical = files = 0
    stack = [(root, "")]
    while stack:
        path, relative = stack.pop()
        require(len(entries) < MAX_ENTRIES, "Cargo tree exceeds 512 total entries")
        before = tree_node(path)
        directory = stat.S_ISDIR(before.st_mode)
        entry = {"kind": "directory" if directory else "file",
                 "mode": base.metadata(before, directory)["mode"],
                 "mtime_ns": before.st_mtime_ns}
        observations[relative] = (path, stable_info(before))
        if directory:
            children = sorted(path.iterdir(), key=lambda child: child.name)
            require(len(entries) + len(stack) + len(children) + 1 <= MAX_ENTRIES,
                    "Cargo tree exceeds 512 total entries")
            folded = set()
            for child in children:
                require(plain_component(child.name), "Unsafe Cargo tree path component")
                require(child.name.casefold() not in folded, "Case-alias Cargo names are unsupported")
                folded.add(child.name.casefold())
                name = relative + "/" + child.name if relative else child.name
                require(len(name) <= 512, "Cargo relative path exceeds the bounded oracle/report contract")
                stack.append((child, name))
        else:
            logical += before.st_size
            files += 1
            require(logical <= MAX_TREE_BYTES, "Cargo source+target exceeds 32 MiB preflight")
            entry.update(size=before.st_size, sha256=base.file_hash(path))
            key = (before.st_dev, before.st_ino)
            identities.setdefault(key, []).append(relative)
        require(stable_info(tree_node(path)) == stable_info(before),
                "Cargo entry changed while reading: " + relative)
        entries[relative] = entry
    groups = []
    for names in identities.values():
        names.sort()
        for name in names:
            info = observations[name][1]
            require(info[4] == len(names), "Cargo hardlink leaves the bounded tree: " + name)
        if len(names) > 1:
            groups.append(names)
    # Retain/recheck all identities after the traversal, not only each local read.
    for relative, (path, before) in observations.items():
        require(stable_info(tree_node(path)) == before,
                "Cargo entry changed during the complete inventory: " + relative)
    return {"entries": dict(sorted(entries.items())), "hardlink_groups": sorted(groups),
            "logical_bytes": logical, "files": files, "entry_count": len(entries),
            "limits": {"tree_bytes": MAX_TREE_BYTES, "file_bytes": MAX_FILE_BYTES,
                       "entries": MAX_ENTRIES}}


def load_fixture(root, generation=None):
    root = Path(root)
    tree_node(root)
    require({p.name for p in root.iterdir()} <=
            {MARKER, "Cargo.toml", "Cargo.lock", ".cargo", "src", "target"},
            "Unexpected Cargo fixture top-level entry")
    marker_info = tree_node(root / MARKER)
    require(stat.S_ISREG(marker_info.st_mode) and marker_info.st_nlink == 1
            and marker_info.st_size <= 16384, "Invalid Cargo marker file")
    marker = json.loads((root / MARKER).read_text(encoding="utf-8"))
    require(isinstance(marker, dict), "Cargo marker must be an object")
    fixture_id = marker.get("fixture_id")
    require(isinstance(fixture_id, str) and str(uuid.UUID(fixture_id)) == fixture_id,
            "Invalid Cargo fixture UUID")
    require(marker == fixture_marker(fixture_id), "Cargo marker differs from the fixed contract")
    for directory, names in (("src", {"lib.rs"}), (".cargo", {"config.toml"})):
        info = tree_node(root / directory)
        require(stat.S_ISDIR(info.st_mode), "Fixed crate directory has wrong type")
        require({p.name for p in (root / directory).iterdir()} == names,
                "Unexpected source/config file")
    for relative, expected in FIXED_FILES.items():
        info = tree_node(root / relative)
        require(stat.S_ISREG(info.st_mode) and info.st_nlink == 1
                and info.st_size == len(expected), "Fixed Cargo file shape changed: " + relative)
        require((root / relative).read_bytes() == expected, "Fixed Cargo file changed: " + relative)
    source_info = tree_node(root / "src/lib.rs")
    require(stat.S_ISREG(source_info.st_mode) and source_info.st_nlink == 1
            and source_info.st_size <= 4096, "Invalid fixed source shape")
    source = (root / "src/lib.rs").read_bytes()
    require(source == SOURCES[generation] if generation is not None else source in SOURCES,
            "Source is not the expected fixed Cargo workload")
    return marker


def fixture_marker(fixture_id):
    return {"schema_version": SCHEMA, "kind": KIND, "fixture_id": fixture_id,
            "crate_name": CRATE, "tree_limit_bytes": MAX_TREE_BYTES,
            "entry_limit": MAX_ENTRIES, "file_limit_bytes": MAX_FILE_BYTES}


def write_new(path, content):
    with Path(path).open("xb") as handle:
        require(handle.write(content) == len(content), "Short fixed-file write")
        handle.flush()
        os.fsync(handle.fileno())


def create_fixture(root):
    root.mkdir(mode=0o755)
    (root / "src").mkdir(mode=0o755)
    (root / ".cargo").mkdir(mode=0o755)
    for relative, content in FIXED_FILES.items():
        write_new(root / relative, content)
    write_new(root / "src/lib.rs", SOURCES[0])
    base.json_new(root / MARKER, fixture_marker(str(uuid.uuid4())))
    return load_fixture(root, 0)


def edit_source(root, before_generation, after_generation):
    require(after_generation == before_generation + 1 and after_generation < len(SOURCES),
            "Only the next fixed source edit is permitted")
    load_fixture(root, before_generation)
    path = Path(root) / "src/lib.rs"
    before = tree_node(path)
    # Do not manufacture a future timestamp. Wait for a distinct real clock tick.
    deadline = time.monotonic() + 2
    while time.time_ns() // 100 <= before.st_mtime_ns // 100:
        require(time.monotonic() < deadline, "Wall clock did not advance for the fixed edit")
        time.sleep(0.01)
    with path.open("r+b") as handle:
        require(handle.read() == SOURCES[before_generation], "Source changed before fixed edit")
        handle.seek(0)
        require(handle.write(SOURCES[after_generation]) == len(SOURCES[after_generation]),
                "Short fixed source edit")
        handle.truncate()
        handle.flush()
        os.fsync(handle.fileno())
    require(tree_node(path).st_mtime_ns > before.st_mtime_ns, "Fixed edit mtime did not advance")
    load_fixture(root, after_generation)


def outside(live, path):
    if os.name == "nt":
        base.outside_volume(live, path)
    else:
        require(live != path and live not in path.parents and path not in live.parents,
                "Output roots must not overlap the live tree")


def new_work(raw, live):
    path = base.ordinary_path(raw, must_exist=False)
    require(path.parent.is_dir() and not path.exists(), "Work root must be new with an existing parent")
    outside(live, path)
    path.mkdir(mode=0o755)
    (path / "logs").mkdir(mode=0o755)
    return path


def executable(raw):
    path = base.ordinary_path(raw)
    base.check_node(path)
    require(path.is_file(), "Expected an already installed executable")
    return path


def cargo_environment(root, cargo_home):
    env = os.environ.copy()
    # Disallow inherited wrappers, flags, profile overrides and alternate targets.
    # Preserve PATH/RUSTUP_HOME so the already installed toolchain remains usable.
    for key in list(env):
        if (key.startswith(("CARGO_PROFILE_", "CARGO_TARGET_", "CARGO_BUILD_"))
                or key in {"RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTDOCFLAGS",
                           "CARGO_ENCODED_RUSTDOCFLAGS", "RUSTC_WRAPPER",
                           "RUSTC_WORKSPACE_WRAPPER", "RUSTC", "RUSTDOC"}):
            env.pop(key)
    controlled = {"CARGO_HOME": str(cargo_home), "CARGO_TARGET_DIR": str(root / "target"),
                  "CARGO_INCREMENTAL": "1", "CARGO_NET_OFFLINE": "true",
                  "CARGO_TERM_COLOR": "never", "CARGO_TERM_PROGRESS_WHEN": "never",
                  "CARGO_BUILD_JOBS": "1", "RUSTUP_AUTO_INSTALL": "0",
                  "TEMP": str(cargo_home / "tmp"), "TMP": str(cargo_home / "tmp")}
    env.update(controlled)
    return env, controlled


class Commands:
    """A fixed-size output pump; never buffer child output without a hard bound."""

    def __init__(self, logs, prefix, timeout):
        require(1 <= timeout <= 300, "Child timeout must be 1..300 seconds")
        self.logs, self.prefix, self.timeout = Path(logs), prefix, timeout
        self.commands = []

    def run(self, argv, cwd, env=None, inherited_handle=None):
        require(len(self.commands) < MAX_COMMANDS, "Fixed command ceiling exhausted")
        number = len(self.commands) + 1
        record = {"argv": [str(arg) for arg in argv], "cwd": str(cwd),
                  "exited": False, "streams_drained": False,
                  "capability_forwarded": inherited_handle is not None}
        self.commands.append(record)
        for stream in ("stdout", "stderr"):
            record[stream + "_log"] = str(self.logs / ("%s-%02d.%s.log" % (self.prefix, number, stream)))
            record[stream] = {"bytes_seen": 0, "bytes_logged": 0, "overflow": False,
                              "eof": False, "error": None, "log_limit_bytes": MAX_LOG_BYTES}

        def drain(pipe, log, state):
            try:
                while True:
                    chunk = pipe.read(64 * 1024)
                    if not chunk:
                        state["eof"] = True
                        break
                    state["bytes_seen"] += len(chunk)
                    state["overflow"] |= state["bytes_seen"] > MAX_LOG_BYTES
                    keep = min(len(chunk), MAX_LOG_BYTES - state["bytes_logged"])
                    if keep and state["error"] is None:
                        try:
                            require(log.write(chunk[:keep]) == keep, "Short bounded child log write")
                            state["bytes_logged"] += keep
                        except BaseException as error:
                            state["error"] = str(error)
            except BaseException as error:
                state["error"] = str(error)
            finally:
                for handle in (pipe, log):
                    try:
                        handle.close()
                    except BaseException as error:
                        state["error"] = str(error)

        kwargs = {"stdout": subprocess.PIPE, "stderr": subprocess.PIPE,
                  "stdin": subprocess.DEVNULL, "shell": False, "close_fds": True,
                  "cwd": str(cwd), "env": env}
        if inherited_handle is not None:
            require(os.name == "nt", "HANDLE forwarding is Windows-only")
            require(type(inherited_handle) is int and 0 < inherited_handle < (1 << (ctypes.sizeof(ctypes.c_void_p) * 8)) - 1,
                    "Invalid inherited directory HANDLE")
            # capture() first binds the received capability and clears its
            # inherited flag. Only this single controlled Popen re-enables it.
            require(not os.get_handle_inheritable(inherited_handle),
                    "Validated snapshot HANDLE must not remain broadly inheritable")
            startup = subprocess.STARTUPINFO()
            startup.lpAttributeList = {"handle_list": [inherited_handle]}
            kwargs["startupinfo"] = startup
        stdout = Path(record["stdout_log"]).open("xb")
        try:
            stderr = Path(record["stderr_log"]).open("xb")
        except BaseException:
            stdout.close()
            raise
        start = time.monotonic()
        process = None
        try:
            if inherited_handle is not None:
                os.set_handle_inheritable(inherited_handle, True)
            try:
                process = subprocess.Popen(record["argv"], **kwargs)
            finally:
                if inherited_handle is not None:
                    os.set_handle_inheritable(inherited_handle, False)
        except BaseException as error:
            stdout.close()
            stderr.close()
            if process is not None:
                raise FixtureError("Could not restore capability inheritance after child creation; retain state",
                                   uncertain_child=True, child_pid=process.pid) from error
            raise
        record["pid"] = process.pid
        threads = [threading.Thread(target=drain, args=(process.stdout, stdout, record["stdout"]), daemon=True),
                   threading.Thread(target=drain, args=(process.stderr, stderr, record["stderr"]), daemon=True)]
        for thread in threads:
            thread.start()
        deadline = start + self.timeout
        try:
            status = process.wait(timeout=self.timeout)
        except subprocess.TimeoutExpired:
            raise FixtureError("Child timed out; retain snapshot, volume and owned files without killing/retrying",
                               uncertain_child=True, child_pid=process.pid, argv=record["argv"])
        record.update(exited=True, returncode=status, seconds=time.monotonic() - start)
        for thread in threads:
            thread.join(max(0, deadline - time.monotonic()))
        if any(thread.is_alive() for thread in threads):
            raise FixtureError("Child output is not drained; a descendant may still be active; retain state",
                               uncertain_child=True, child_pid=process.pid, argv=record["argv"])
        record["streams_drained"] = all(record[s]["eof"] for s in ("stdout", "stderr"))
        require(record["streams_drained"] and not any(record[s]["error"] for s in ("stdout", "stderr")),
                "Child output drain/write failed")
        require(not any(record[s]["overflow"] for s in ("stdout", "stderr")),
                "Child exceeded the fixed 512 KiB per-stream log cap; output is not trusted")
        require(status == 0, "Child failed; see retained bounded log: " + record["stderr_log"])
        output = []
        for stream in ("stdout", "stderr"):
            path = Path(record[stream + "_log"])
            require(path.stat().st_size <= MAX_LOG_BYTES, "Child log cap was violated")
            output.append(path.read_text(encoding="utf-8", errors="replace"))
        return output[0], output[1], record

    def safe(self):
        return all(command.get("exited") and command.get("streams_drained") for command in self.commands)


def cargo_result(stdout, stderr, expect_fresh):
    """Require positive Cargo/test evidence, not merely absence of an error."""
    output = stdout + "\n" + stderr
    fresh = bool(re.search(r"(?m)^\s*Fresh\s+" + CRATE + r"\s+v0\.1\.0(?:\s|$)", output))
    compiling = bool(re.search(r"(?m)^\s*Compiling\s+" + CRATE + r"\s+v0\.1\.0(?:\s|$)", output))
    rustc = bool(re.search(r"(?mi)^\s*Running\s+[^\r\n]*\brustc(?:\.exe)?\b", output))
    passed = bool(re.search(r"(?m)^test result: ok\. 1 passed; 0 failed;", output))
    case = bool(re.search(r"(?m)^test tests::fixed_workload_result \.\.\. ok\s*$", output))
    require(passed and case, "The fixed unit test did not explicitly pass")
    require(fresh and not compiling and not rustc if expect_fresh else compiling and not fresh and rustc,
            "Expected explicit Fresh with no compilation" if expect_fresh
            else "Expected explicit compilation and rustc execution for the changed/clean crate")
    return {"fresh": fresh, "compiling": compiling, "rustc_invoked": rustc,
            "fixed_test_passed": passed and case, "expect_fresh": expect_fresh}


def run_cargo(commands, cargo, root, cargo_home, expect_fresh):
    env, controlled = cargo_environment(root, cargo_home)
    stdout, stderr, record = commands.run([str(cargo)] + TEST_ARGS, root, env=env)
    result = cargo_result(stdout, stderr, expect_fresh)
    result.update(seconds=record["seconds"], environment=controlled,
                  stdout_log=record["stdout_log"], stderr_log=record["stderr_log"])
    load_fixture(root)
    tree = inventory(root)
    result["tree_summary"] = {key: tree[key] for key in ("logical_bytes", "files", "entry_count")}
    result["tree_summary"]["hardlink_groups"] = len(tree["hardlink_groups"])
    require(base.measure(cargo_home)["logical_bytes"] <= MAX_CARGO_HOME_BYTES,
            "Isolated Cargo home exceeds its 8 MiB allowance")
    return result, tree


def report_base(stage, live, work, commands):
    return {"schema_version": SCHEMA, "kind": KIND, "stage": stage,
            "status": "failed", "cleanup_safe": False, "live_root": str(live),
            "work_root": str(work), "commands": commands.commands,
            "limits": {"source_and_target_bytes": MAX_TREE_BYTES, "file_bytes": MAX_FILE_BYTES,
                       "entries": MAX_ENTRIES, "log_bytes_per_stream": MAX_LOG_BYTES,
                       "report_bytes": MIB, "cargo_home_bytes": MAX_CARGO_HOME_BYTES},
            "limitations": ["Settled Cargo workload, not concurrent application atomicity.",
                "No ACL, owner, creation-time or access-time equivalence claim.",
                "Supported Windows mode, mtime, every byte and hardlink topology are checked.",
                "Preflight/checkpoint sizes are not filesystem quotas or continuous physical peaks.",
                "A Fresh result is required from Cargo output, never inferred from saved timestamps."]}


def finish_report(work, filename, report, commands, action):
    started = time.monotonic()
    try:
        action()
        require(commands.safe(), "Not all direct children exited and drained")
        report.update(status="passed", cleanup_safe=True, all_direct_children_exited=True,
                      all_direct_child_pipes_drained=True, total_seconds=time.monotonic() - started)
    except BaseException as error:
        report.update(error=str(error), **getattr(error, "details", {}))
        report["all_direct_children_exited"] = all(c.get("exited") for c in commands.commands)
        report["all_direct_child_pipes_drained"] = all(c.get("streams_drained") for c in commands.commands)
        base.json_new(work / filename, report)
        raise FixtureError(str(error), report_path=str(work / filename), **getattr(error, "details", {}))
    base.json_new(work / filename, report)
    return report


def cargo_version(commands, cargo, cwd, cargo_home):
    env, _ = cargo_environment(cwd, cargo_home)
    stdout, stderr, _ = commands.run([str(cargo), "--version"], cwd, env=env)
    require(bool(re.fullmatch(r"cargo [^\r\n]+\r?\n?", stdout)) and not stderr.strip(),
            "Expected an already installed Cargo version, not a toolchain setup flow")
    return stdout.strip()


def prepare(args):
    require(os.name == "nt", "Cargo VSS prepare is restricted to the disposable Windows runner")
    live = base.ordinary_path(args.live_root, must_exist=False)
    require(live.parent.is_dir() and not live.exists(), "Live Cargo fixture must be new")
    cargo = executable(args.cargo)
    work = new_work(args.work_root, live)
    commands = Commands(work / "logs", "cargo", args.timeout)
    report = report_base("prepare", live, work, commands)

    def action():
        cargo_home = work / "cargo-home"
        cargo_home.mkdir()
        (cargo_home / "tmp").mkdir()
        marker = create_fixture(live)
        report.update(fixture_id=marker["fixture_id"], cargo=str(cargo), cargo_home=str(cargo_home),
                      cargo_manifest=MANIFEST.decode("ascii"), cargo_config=CONFIG.decode("ascii"),
                      cargo_test_arguments=TEST_ARGS,
                      profile={"debug": 0, "incremental": True, "codegen_units": 1,
                               "jobs": 1, "dependencies": []})
        report["cargo_version"] = cargo_version(commands, cargo, live, cargo_home)
        require(not (live / "target").exists(), "Clean build unexpectedly has an existing target")
        report["clean"], clean_tree = run_cargo(commands, cargo, live, cargo_home, False)
        require(any(name.startswith("target/debug/incremental/") and item["kind"] == "file"
                    and item["size"] > 0 for name, item in clean_tree["entries"].items()),
                "Cargo incremental artifact files are missing")
        report["noop"], noop_tree = run_cargo(commands, cargo, live, cargo_home, True)
        report["noop_changed_entries"] = changed_entries(clean_tree, noop_tree)
        edit_source(live, 0, 1)
        report["edited"], expected = run_cargo(commands, cargo, live, cargo_home, False)
        load_fixture(live, 1)
        require(inventory(live) == expected, "Settled edited tree changed on repeated complete read")
        report.update(pre_snapshot_inventory=expected, pre_snapshot_size_verified=True,
                      live_storage=base.measure(live), cargo_home_storage=base.measure(cargo_home),
                      work_storage_before_report=base.measure(work), snapshot_ready=True)

    return finish_report(work, "prepare.json", report, commands, action)


def verified_prepare(path, live=None):
    report = bounded_json(path)
    require(report.get("schema_version") == SCHEMA and report.get("kind") == KIND
            and report.get("stage") == "prepare" and report.get("status") == "passed"
            and report.get("cleanup_safe") is True and report.get("snapshot_ready") is True
            and report.get("pre_snapshot_size_verified") is True,
            "Prepare report is not a completed bounded Cargo workload")
    if live is not None:
        require(report.get("live_root") == str(live), "Prepare report belongs to a different live root")
    return report


def sprig_result(commands, binary, store, *args, inherited_handle=None):
    stdout, _, _ = commands.run([str(binary), "--store", str(store), "--json"] + list(args),
                                commands.logs.parent, inherited_handle=inherited_handle)
    envelope = json.loads(stdout)
    require(isinstance(envelope, dict) and envelope.get("schema_version") == 1 and "result" in envelope,
            "Unexpected Sprig JSON envelope")
    result = envelope["result"]
    require(not isinstance(result, dict) or not result.get("mount_error"), "Partial Sprig mount outcome")
    return result


def bind_snapshot_handle(handle, expected_root, expected_serial):
    """Bind the independent pathname oracle to the received root capability first."""
    require(os.name == "nt", "Snapshot capability binding is Windows-only")
    from ctypes import wintypes

    class HandleInfo(ctypes.Structure):
        _fields_ = [("attributes", ctypes.c_uint32),
                    ("creation_time", ctypes.c_uint32 * 2),
                    ("access_time", ctypes.c_uint32 * 2),
                    ("write_time", ctypes.c_uint32 * 2),
                    ("volume_serial", ctypes.c_uint32),
                    ("size_high", ctypes.c_uint32), ("size_low", ctypes.c_uint32),
                    ("links", ctypes.c_uint32),
                    ("index_high", ctypes.c_uint32), ("index_low", ctypes.c_uint32)]

    assert ctypes.sizeof(HandleInfo) == 52 and HandleInfo.volume_serial.offset == 28
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    final_name = kernel.GetFinalPathNameByHandleW
    final_name.argtypes = [wintypes.HANDLE, wintypes.LPWSTR, wintypes.DWORD, wintypes.DWORD]
    final_name.restype = wintypes.DWORD
    get_info = kernel.GetFileInformationByHandle
    get_info.argtypes = [wintypes.HANDLE, ctypes.POINTER(HandleInfo)]
    get_info.restype = wintypes.BOOL
    get_type = kernel.GetFileType
    get_type.argtypes = [wintypes.HANDLE]
    get_type.restype = wintypes.DWORD
    require(get_type(handle) == 1, "Snapshot capability is not a disk filesystem handle")
    name = ctypes.create_unicode_buffer(32768)
    length = final_name(handle, name, len(name), 2)  # VOLUME_NAME_NT, normalized file name.
    if length == 0:
        raise ctypes.WinError(ctypes.get_last_error())
    require(length < len(name), "Snapshot capability final path is too long")
    prefix = "\\\\?\\GLOBALROOT"
    require(str(expected_root).startswith(prefix)
            and name.value == str(expected_root)[len(prefix):],
            "Snapshot pathname is not bound to the inherited directory HANDLE")
    info = HandleInfo()
    if not get_info(handle, ctypes.byref(info)):
        raise ctypes.WinError(ctypes.get_last_error())
    require(info.attributes & 0x10 and not info.attributes & 0x400,
            "Snapshot capability is not a no-reparse directory")
    require(info.volume_serial == int(expected_serial, 16), "Snapshot capability volume serial differs")
    # The requester retains ownership. Do not close or duplicate its capability.
    return {"path_bound_before_oracle": True, "serial_verified": True,
            "directory_no_reparse_verified": True,
            "granted_access_validation": "Controlled importer checks read-only access before ingestion; Python does not elevate access."}


def capture(args):
    require(os.name == "nt", "Capture requires the Windows requester's held snapshot")
    require(VSS_ROOT.fullmatch(args.snapshot_root) is not None, "Invalid requester snapshot root")
    require(args.relative_path == "fixture", "Only the fixed synthetic fixture descendant is permitted")
    require(re.fullmatch(r"[a-z][a-z0-9-]{0,31}", args.label) is not None, "Unsafe capture label")
    require(re.fullmatch(r"[0-9A-Fa-f]{8}", args.serial) is not None
            and re.fullmatch(r"[0-9A-Fa-f]{32}", args.marker_token) is not None, "Invalid snapshot identity")
    require(re.fullmatch(r"[1-9][0-9]{0,19}", args.snapshot_handle) is not None,
            "Snapshot HANDLE must be canonical positive decimal")
    handle = int(args.snapshot_handle)
    require(handle < (1 << (ctypes.sizeof(ctypes.c_void_p) * 8)) - 1
            and os.get_handle_inheritable(handle), "Missing inherited requester directory capability")
    live = base.ordinary_path(args.live_root)
    _, mounted_root = base.volume(live)
    require(os.path.normcase(str(Path(mounted_root) / "fixture")) == os.path.normcase(str(live)),
            "Live root must be the source volume's fixed fixture directory")
    prepared = verified_prepare(args.prepare_report, live)
    snapshot = Path(args.snapshot_root) / "fixture"
    capability = bind_snapshot_handle(handle, snapshot, args.serial)
    os.set_handle_inheritable(handle, False)
    require(not os.get_handle_inheritable(handle), "Could not clear inherited snapshot HANDLE flag")
    capability["inheritance_cleared_before_children"] = True
    identity = base.snapshot_identity(args.snapshot_root)
    require(identity["serial"].upper() == args.serial.upper()
            and identity["marker_token"].lower() == args.marker_token.lower(),
            "Snapshot synthetic volume identity differs from requester expectations")
    require(load_fixture(live, 1) == load_fixture(snapshot, 1), "Snapshot fixture identity differs from live")
    binary = executable(args.sprig)
    store = base.ordinary_path(args.store, must_exist=False)
    require(store.parent.is_dir() and not store.exists(), "Cargo capture requires a NEW store")
    outside(live, store)
    work = new_work(args.work_root, live)
    require(work != store and work not in store.parents and store not in work.parents,
            "Capture store and work roots overlap")
    commands = Commands(work / "logs", "sprig", args.timeout)
    report = report_base("capture", live, work, commands)
    report.update(label=args.label, fixture_id=prepared["fixture_id"], store=str(store),
                  prepare_report=str(base.ordinary_path(args.prepare_report)),
                  snapshot_root=args.snapshot_root, snapshot_fixture=str(snapshot),
                  cas_import_mode="inherited_snapshot_tree_capability", staging_mode="none",
                  snapshot_capability=capability,
                  capability_forwarding="STARTUPINFO handle_list contains exactly the requester root handle",
                  serial=args.serial.upper(), marker_token=args.marker_token)

    def action():
        started = time.monotonic()
        expected = inventory(snapshot)
        require(inventory(snapshot) == expected, "Snapshot changed between complete oracle reads")
        require(expected == prepared["pre_snapshot_inventory"],
                "Settled snapshot differs from bounded edited preflight")
        require(inventory(live) == expected, "Live settled source changed before capture")
        report.update(snapshot_inventory=expected, snapshot_read_verified=True,
                      snapshot_oracle_seconds=time.monotonic() - started,
                      snapshot_storage=base.measure(snapshot), staging_storage=base.measure(work / "stage"))
        owner = Path(str(store) + ".sprig-vss-owner.json")
        require(not owner.exists(), "Orphan Cargo store ownership marker requires inspection")
        base.json_new(owner, {"schema_version": SCHEMA, "kind": KIND,
                             "fixture_id": prepared["fixture_id"], "store": str(store)})
        sprig_result(commands, binary, store, "init")
        before = sprig_result(commands, binary, store, "stats")
        report["sprig_stats_before_import"] = before
        report["store_storage_before_import"] = base.measure(store)
        name = "vss-" + args.label + "-" + uuid.uuid4().hex
        started = time.monotonic()
        imported = sprig_result(commands, binary, store, "snapshot-import-tree-experiment",
                                str(snapshot), name, "--root-handle", str(handle),
                                "--serial", args.serial, "--marker-token", args.marker_token,
                                inherited_handle=handle)
        report["cas_import_seconds"] = time.monotonic() - started
        require(imported.get("backend", {}).get("kind") == "writable"
                and imported.get("mount_state") == "unmounted", "Import was not unmounted writable CAS")
        revision = imported.get("base_revision")
        require(isinstance(revision, str) and re.fullmatch(r"[0-9a-f]{64}", revision),
                "Invalid imported revision identity")
        report.update(import_name=name, imported_revision=revision)
        after = sprig_result(commands, binary, store, "stats")
        report.update(sprig_stats_after_import=after, store_storage_after_import=base.measure(store),
                      import_storage_delta=base.delta(before, after,
                          ("objects", "object_bytes", "object_storage_bytes", "store_logical_bytes", "store_allocated_bytes")))
        started = time.monotonic()
        restored = sprig_result(commands, binary, store, "--copy", "restore", revision, name + "-restore")
        require(restored.get("backend", {}).get("kind") == "native"
                and restored.get("mount_state") == "native", "Restore was not native materialization")
        restore = base.ordinary_path(base.restore_drive_path(restored["path"]))
        require(store in restore.parents, "Native restore escaped the owned CAS store")
        outside(live, restore)
        require(load_fixture(restore, 1) == load_fixture(snapshot, 1), "Restored fixture identity differs")
        require(inventory(restore) == expected,
                "Native restore differs in bytes, namespace, modes, mtimes or hardlink topology")
        require(inventory(snapshot) == expected, "Snapshot changed during CAS import/restore")
        report.update(cas_restore_path=str(restore), cas_restore_seconds=time.monotonic() - started,
                      cas_native_restore_verified=True, full_bytes_mode_mtime_hardlinks_verified=True,
                      restore_storage=base.measure(restore),
                      sprig_stats_after_restore=sprig_result(commands, binary, store, "stats"),
                      store_storage_after_restore=base.measure(store),
                      work_storage_before_report=base.measure(work))

    return finish_report(work, "capture.json", report, commands, action)


def changed_entries(before, after):
    return [name for name in sorted(set(before["entries"]) | set(after["entries"]))
            if before["entries"].get(name) != after["entries"].get(name)]


def finalize(args):
    require(os.name == "nt", "Finalize is restricted to the disposable Windows runner")
    captured = bounded_json(args.capture_report)
    require(captured.get("schema_version") == SCHEMA and captured.get("kind") == KIND
            and captured.get("stage") == "capture" and captured.get("status") == "passed"
            and captured.get("cleanup_safe") is True
            and captured.get("full_bytes_mode_mtime_hardlinks_verified") is True,
            "Capture report is not a successful capability import/native restore")
    live = base.ordinary_path(captured["live_root"])
    prepared = verified_prepare(args.prepare_report, live)
    require(captured["fixture_id"] == prepared["fixture_id"]
            and captured["prepare_report"] == str(base.ordinary_path(args.prepare_report)),
            "Reports do not belong to the same Cargo run")
    cargo = executable(args.cargo)
    require(str(cargo) == prepared["cargo"], "Finalize must use the same installed Cargo executable")
    cargo_home = base.ordinary_path(prepared["cargo_home"])
    prepare_work = base.ordinary_path(prepared["work_root"])
    require(cargo_home == prepare_work / "cargo-home", "Cargo home is outside its owned prepare work")
    store = base.ordinary_path(captured["store"])
    restore = base.ordinary_path(captured["cas_restore_path"])
    require(store in restore.parents, "Restored Cargo root is outside its owned store")
    outside(live, restore)
    work = new_work(args.work_root, live)
    require(work != store and work not in store.parents and store not in work.parents,
            "Finalize diagnostics must not overlap the CAS store")
    commands = Commands(work / "logs", "cargo", args.timeout)
    report = report_base("finalize", live, work, commands)
    report.update(fixture_id=prepared["fixture_id"], store=str(store), cas_restore_path=str(restore),
                  prepare_report=str(base.ordinary_path(args.prepare_report)),
                  capture_report=str(base.ordinary_path(args.capture_report)),
                  original_cargo_target_dir=str(live / "target"),
                  restored_cargo_target_dir=str(restore / "target"),
                  cargo_target_paths_equal=os.path.normcase(str(live / "target")) ==
                                          os.path.normcase(str(restore / "target")),
                  relocation_policy="Do not edit fingerprints, dep-info, artifact metadata or timestamps to force Fresh; a rebuild is a failed Fresh acceptance with retained output.")

    def action():
        require(load_fixture(restore, 1)["fixture_id"] == prepared["fixture_id"], "Restored marker changed")
        expected = captured["snapshot_inventory"]
        require(inventory(restore) == expected, "Restored tree changed before Fresh validation")
        require(inventory(live) == prepared["pre_snapshot_inventory"], "Live source changed before finalize")
        version = cargo_version(commands, cargo, restore, cargo_home)
        require(version == prepared["cargo_version"], "Installed Cargo version changed between phases")
        report["cargo_version"] = version
        report["restored_noop"], noop_tree = run_cargo(commands, cargo, restore, cargo_home, True)
        report["restored_noop_changed_entries"] = changed_entries(expected, noop_tree)
        # Cargo may legitimately refresh housekeeping metadata. Record every
        # difference instead of claiming that Fresh means byte-for-byte stasis.
        report["fresh_verified"] = True
        edit_source(restore, 1, 2)
        report["continued_edit"], final_tree = run_cargo(commands, cargo, restore, cargo_home, False)
        require(load_fixture(restore, 2)["fixture_id"] == prepared["fixture_id"], "Continued marker changed")
        require(inventory(live) == prepared["pre_snapshot_inventory"],
                "Editing the native restore changed the original live tree")
        report.update(continued_normal_workflow_verified=True, original_live_tree_unchanged=True,
                      final_restore_inventory=final_tree, restore_storage=base.measure(restore),
                      store_storage=base.measure(store), cargo_home_storage=base.measure(cargo_home),
                      work_storage_before_report=base.measure(work))

    return finish_report(work, "finalize.json", report, commands, action)


def selftest():
    """No executable except this Python interpreter is launched by this test."""
    with tempfile.TemporaryDirectory(prefix="sprig-vss-cargo-selftest-") as temporary:
        root = Path(temporary)
        require(all(plain_component(name) for name in ("Cargo.toml", ".cargo", "test-123.exe")),
                "Ordinary path component rejected")
        require(not any(plain_component(name) for name in ("..", "a:b", "a/b", "a\\b", "x.", "x ", "CON", "NUL.txt")),
                "Unsafe path component accepted")
        live = root / "fixture"
        create_fixture(live)
        before = inventory(live)
        require(inventory(live) == before, "Repeated oracle selftest differs")
        edit_source(live, 0, 1)
        require(inventory(live) != before, "Fixed edit selftest did not change inventory")
        target = live / "target"
        target.mkdir()
        write_new(target / "one", b"bounded hardlink oracle\n")
        os.link(target / "one", target / "two")
        linked = inventory(live)
        require(linked["hardlink_groups"] == [["target/one", "target/two"]], "Hardlink topology was lost")
        os.link(target / "one", root / "outside-link")
        try:
            inventory(live)
        except FixtureError as error:
            require("leaves the bounded tree" in str(error), "External hardlink failed for wrong reason")
        else:
            raise FixtureError("External hardlink unexpectedly accepted")
        (root / "outside-link").unlink()
        test = "test tests::fixed_workload_result ... ok\ntest result: ok. 1 passed; 0 failed; 0 ignored\n"
        cargo_result(test, "       Fresh " + CRATE + " v0.1.0\n", True)
        cargo_result(test, "   Compiling " + CRATE + " v0.1.0\n     Running `rustc --crate-name test`\n", False)
        for stderr in ("", "       Fresh " + CRATE + " v0.1.0\n   Compiling " + CRATE + " v0.1.0\n"):
            try:
                cargo_result(test, stderr, True)
            except FixtureError:
                pass
            else:
                raise FixtureError("Missing/contradictory Fresh evidence was accepted")
        logs = root / "logs"
        logs.mkdir()
        commands = Commands(logs, "mock", 5)
        real_popen = subprocess.Popen

        class FakeProcess:
            pid = 0

            def __init__(self, out, err):
                self.stdout, self.stderr = io.BytesIO(out), io.BytesIO(err)

            def wait(self, timeout):
                return 0

        try:
            subprocess.Popen = lambda *a, **k: FakeProcess(b"small\n", b"")
            require(commands.run(["not-executed"], root)[0] == "small\n", "Bounded output selftest failed")
            subprocess.Popen = lambda *a, **k: FakeProcess(b"x" * (MAX_LOG_BYTES + 7), b"y" * (MAX_LOG_BYTES + 9))
            try:
                commands.run(["not-executed"], root)
            except FixtureError as error:
                require("512 KiB" in str(error), "Log overflow failed for wrong reason")
            else:
                raise FixtureError("Log overflow unexpectedly accepted")
            record = commands.commands[-1]
            require(record["exited"] and record["streams_drained"], "Overflow streams did not drain")
            for stream in ("stdout", "stderr"):
                require(Path(record[stream + "_log"]).stat().st_size == MAX_LOG_BYTES,
                        "Bounded log exceeded its limit")
        finally:
            subprocess.Popen = real_popen
        oversized = root / "oversized.json"
        try:
            base.json_new(oversized, {"payload": "x" * MIB})
        except FixtureError:
            require(not oversized.exists(), "Oversized report created a file before refusal")
        else:
            raise FixtureError("Oversized report was accepted")
        require(base.measure(root)["logical_bytes"] < 2 * MIB, "Selftest exceeded its tiny ordinary-file allowance")
    return {"schema_version": SCHEMA, "status": "selftest_passed", "cargo_executed": False,
            "sprig_executed": False, "vss_executed": False,
            "checks": ["fixed crate and edits", "full repeated oracle", "internal hardlinks",
                       "external hardlinks rejected", "safe path components", "bounded JSON before write",
                       "positive Fresh/compile/test evidence", "bounded mock stdout/stderr drains"]}


def parser():
    result = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = result.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare")
    for flag in ("live-root", "work-root", "cargo"):
        prep.add_argument("--" + flag, required=True)
    capture_parser = sub.add_parser("capture")
    capture_parser.add_argument("snapshot_root")
    for flag in ("snapshot-handle", "serial", "marker-token", "relative-path", "live-root",
                 "work-root", "store", "sprig", "prepare-report", "label"):
        capture_parser.add_argument("--" + flag, required=True)
    final = sub.add_parser("finalize")
    for flag in ("capture-report", "prepare-report", "cargo", "work-root"):
        final.add_argument("--" + flag, required=True)
    for command in (prep, capture_parser, final):
        command.add_argument("--timeout", type=int, default=300)
    sub.add_parser("selftest")
    return result


def main():
    args = parser().parse_args()
    try:
        result = {"prepare": prepare, "capture": capture, "finalize": finalize}.get(args.command)
        base.emit(result(args) if result is not None else selftest())
        return 0
    except BaseException as error:
        base.emit({"schema_version": SCHEMA, "status": "failed", "cleanup_safe": False,
                   "error": str(error), **getattr(error, "details", {}),
                   "instruction": "Retain owned state; do not kill children, force snapshot deletion or force-detach the volume."})
        return 1


if __name__ == "__main__":
    sys.exit(main())
