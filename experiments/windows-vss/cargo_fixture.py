"""Bounded, dependency-free Cargo acceptance for the held VSS tree capability.

This helper never creates/deletes snapshots, mounts/detaches disks, installs a
toolchain, or deletes an existing tree. The requester owns snapshot lifetime.
The ordinary source/target tree is at most 32 MiB, 512 entries and 16 MiB/file.
These are fail-closed preflight/checkpoint bounds, not filesystem write quotas.

Windows / Python 3.9+ / an already installed Cargo and Rust toolchain:
  prepare --live-root NEW_DIR --work-root NEW_OUTSIDE_DIR --cargo ABSOLUTE_EXE
  capture SNAPSHOT_ROOT --snapshot-handle DECIMAL --serial HEX8
          --marker-token HEX32 --relative-path fixture --live-root DIR
          --work-root NEW_OUTSIDE_DIR --store NEW_OUTSIDE_STORE
          --sprig ABSOLUTE_EXE --prepare-report FILE --label cargo-edited
  finalize --capture-report FILE --prepare-report FILE --cargo ABSOLUTE_EXE
           --work-root NEW_OUTSIDE_DIR
  selftest   # Tiny ordinary local files only; no Cargo, Sprig or VSS execution.

Only the controlled import inherits the explicitly supplied directory HANDLE.
The snapshot pathname is a binding assertion and independent read-only oracle,
not a substitute for that capability. There is no staged source copy.
Timed-out or undrained children are neither killed nor retried; retain state.
"""

